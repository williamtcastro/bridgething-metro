// unknown ids fall back to their last segment, split at case changes: com.foo.MyGreatApp -> My Great App
export function appName(bundleId: string) {
  const known = APP_NAMES[bundleId];
  if (known) return known;
  const last = bundleId.split('.').pop() ?? bundleId;
  return last.replace(/^(Mobile|mobile)(?=[A-Z])/, '').replace(/([a-z])([A-Z])/g, '$1 $2') || bundleId;
}
